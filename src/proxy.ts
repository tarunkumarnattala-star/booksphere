import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";
import { books, genres } from "@/lib/data";

// Book and genre pages await Supabase, which makes them dynamic. A dynamic route runs
// even when its param is not in generateStaticParams, and notFound() from inside a
// running page renders the right screen but still answers HTTP 200 - a soft 404 that a
// crawler indexes as real content. dynamicParams = false only gates prerendered routes,
// which is why the reading-path route was fixed by it and these were not.
//
// Checking the slug here happens before the page runs, so the answer is a real 404
// regardless of how the route renders. The sets are derived from the catalog rather
// than duplicated, so they cannot drift out of step with it.
const bookSlugs = new Set(books.map((book) => book.id));
const genreSlugs = new Set(genres.map((genre) => genre.slug));

// Profiles and perspectives were left open here because, unlike books and genres, what
// exists is created at runtime and cannot be listed at build time. They kept answering 200
// for anything typed at them, so a crawler could mint unlimited "real" pages.
//
// Both other ways out were tried and failed: notFound() from generateMetadata does not move
// the status (a malformed id never reaches a lookup and still answered 200), and swapping
// force-dynamic for on-demand ISR did not either - built and served locally, a nonexistent
// perspective still answered 200. Whatever commits the status runs before any application
// code, so the proxy is the only place left that is early enough.
//
// The rule is: anything already known to exist passes with no lookup at all; anything else
// costs one indexed query, once, and is then remembered. That keeps the cost on crawler junk
// rather than on readers, and a perspective published seconds ago still resolves, which a
// periodically-refreshed list of ids would not.
const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL;
const SUPABASE_KEY = process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

// Accounts that exist in the database but are not people. A QA probe account was live and
// browsable in production with a machine-generated name; it owns no posts, comments, likes or
// follows, so nothing is orphaned by hiding it. This only makes it unreachable - the row is
// still there, and deleting it is a dashboard job, recorded in launch/MANUAL_TASKS.md.
const INTERNAL_ACCOUNTS = new Set<string>(["booksphere-qa-probe-tri-a71c6f"]);

const knownProfiles = new Set<string>();
const knownPerspectives = new Set<string>();

async function existsInTable(table: string, column: string, value: string) {
  if (!SUPABASE_URL || !SUPABASE_KEY) return true;
  const url = `${SUPABASE_URL}/rest/v1/${table}?select=${column}&${column}=eq.${encodeURIComponent(value)}&limit=1`;
  const response = await fetch(url, {
    headers: { apikey: SUPABASE_KEY, Accept: "application/json" },
    cache: "no-store"
  });
  if (!response.ok) throw new Error(`lookup failed: ${response.status}`);
  const rows = (await response.json()) as unknown[];
  return Array.isArray(rows) && rows.length > 0;
}

async function resolves(kind: "profile" | "perspective", value: string) {
  const seen = kind === "profile" ? knownProfiles : knownPerspectives;
  if (seen.has(value)) return true;
  try {
    const found = kind === "profile"
      ? await existsInTable("profiles", "username", value)
      : await existsInTable("discussion_posts", "id", value);
    if (found) seen.add(value);
    return found;
  } catch {
    // If the database cannot be reached, let the request through. Hiding a real reader's
    // page behind a 404 during an outage is far worse than a soft 404 on a junk URL.
    return true;
  }
}

export const config = {
  matcher: ["/book/:path*", "/genre/:path*", "/profile/:path*", "/discussion/:path*"]
};

export default async function proxy(request: NextRequest) {
  const segments = request.nextUrl.pathname.split("/").filter(Boolean);
  const [section, slug] = segments;

  if (!slug) return NextResponse.next();
  if (section === "book" && !bookSlugs.has(slug)) return notFound(request);
  if (section === "genre" && !genreSlugs.has(slug)) return notFound(request);

  if (section === "profile") {
    // Usernames are generated by the app and never contain anything else, so a value that
    // cannot be one is rejected without troubling the database.
    if (!/^[a-z0-9][a-z0-9-]{1,62}$/.test(slug)) return notFound(request);
    if (INTERNAL_ACCOUNTS.has(slug)) return notFound(request);
    if (!(await resolves("profile", slug))) return notFound(request);
  }

  if (section === "discussion") {
    if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(slug)) return notFound(request);
    if (!(await resolves("perspective", slug))) return notFound(request);
  }

  return NextResponse.next();
}

function notFound(request: NextRequest) {
  // Rewrite rather than redirect: the reader keeps the URL they typed, sees the app's
  // own not-found screen, and the response carries a genuine 404.
  return NextResponse.rewrite(new URL("/not-found", request.url), { status: 404 });
}
